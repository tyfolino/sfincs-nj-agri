"""NRCS easements in the model domain vs tidal exposure and land-use history.

Each NRCS easement (scripts/fetch_easements.py) inside the domain's three counties gets, on
the 30 m grid of scripts/bayshore_exposure.py (`load_grid`):
  area, median height above recent MHHW, share below MHHW + 0.6 m and + 1.5 m, share inside
  an NLD leveed area, CDL cropland and wetland share early (2008-12) and late (2021-25),
and the imagery spot-check samples (data/imagery/spotcheck_samples.csv) that fall inside.

Program groups:
  wetland   WRP, EWRP, ACEP-WRE, RCPP-WRE, EWPP-FPE (floodplain easement): land taken
            out of production and restored / kept as wetland or floodplain
  farmland  FRPP, ACEP-ALE, RCPP-ALE, GRP: development rights bought, farming continues
  other     anything else (e.g. bare "ACEP")
The farmland group is the natural comparison: both are voluntary, paid, permanent
easements; only one takes land out of production.

Writes reports/easement_exposure.md and reports/figs/easement_exposure.png.
Usage:  python scripts/easement_exposure.py
"""

from __future__ import annotations

import geopandas as gpd
import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from rasterio.features import rasterize

import bayshore_exposure as be
from agri_sfincs import cdl, config, domain, region
from agri_sfincs.report import md_table

EASE = config.DATA / "easements" / "nrcs_easements.gpkg"
SAMPLES = config.DATA / "imagery" / "spotcheck_samples.csv"
WETLAND = {"WRP", "EWRP", "ACEP-WRE", "RCPP-WRE", "EWPP-FPE"}
FARMLAND = {"FRPP", "ACEP-ALE", "RCPP-ALE", "GRP"}
WET_CODES = (87, 190, 195)


def group(program: str) -> str:
    return "wetland" if program in WETLAND else "farmland" if program in FARMLAND else "other"


def share(years, codes, win) -> np.ndarray:
    return np.mean([np.isin(be.read_cdl(y, win), list(codes)) for y in years], axis=0)


def main() -> None:
    G = be.load_grid()
    e = gpd.read_file(EASE, layer="boundaries")
    e = e[e.adminfips.isin(domain.COUNTIES)].to_crs(G.crs).reset_index(drop=True)
    e["group"] = e.program.map(group)
    lab = rasterize([(g, i + 1) for i, g in enumerate(e.geometry)], out_shape=G.shape,
                    transform=G.tr, fill=0, dtype="int32")  # fmt: skip
    lev = gpd.read_file(be.STRUCT, layer="nld_leveed_areas").to_crs(G.crs)
    leveed = rasterize([(g, 1) for g in lev.geometry], out_shape=G.shape, transform=G.tr,
                       fill=0, dtype="uint8").astype(bool)  # fmt: skip
    crop0 = share(range(2008, 2013), cdl.CROPLAND, G.win)
    crop1 = share(range(2021, 2026), cdl.CROPLAND, G.win)
    wet1 = share(range(2021, 2026), WET_CODES, G.win)
    ok = np.isfinite(G.hab)

    rows = []
    for i, r in e.iterrows():
        m = (lab == i + 1) & ok
        if not m.any():
            continue
        h = G.hab[m]
        rows.append({"id": int(r.uniqueid), "county": r.county, "program": r.program,
                     "group": r.group, "km2": m.sum() * be.PX_KM2,
                     "m_above_mhhw_p50": np.median(h), "pct_below_0.6": 100 * (h < 0.6).mean(),
                     "pct_below_1.5": 100 * (h < 1.5).mean(),
                     "pct_leveed": 100 * leveed[m].mean(),
                     "crop_08_12": 100 * crop0[m].mean(), "crop_21_25": 100 * crop1[m].mean(),
                     "wetland_21_25": 100 * wet1[m].mean()})  # fmt: skip
    t = pd.DataFrame(rows)

    # imagery samples that fall in an easement
    s = pd.read_csv(SAMPLES)
    hit = lab[s.row.values, s["col"].values] if {"row", "col"} <= set(s.columns) else None
    if hit is None:  # the CSV drops row/col: locate by lon/lat
        pts = gpd.GeoSeries(gpd.points_from_xy(s.lon, s.lat), crs=4326).to_crs(G.crs)
        hit = np.array([lab[int((p.y - G.tr.f) / G.tr.e), int((p.x - G.tr.c) / G.tr.a)] for p in pts])
    s["easement"] = [str(int(e.uniqueid.iloc[k - 1])) if k else None for k in hit]
    in_e = s[s.easement.notna()][["id", "kind", "easement", "cdl_history"]]
    in_e["cdl_history"] = in_e.cdl_history.str.replace("|", " / ")  # "|" would split the table

    def wmean(d, c):
        return np.average(d[c], weights=d.km2)

    summ = pd.DataFrame({g: {"easements": len(d), "km2": d.km2.sum(),
                             **{c: wmean(d, c) for c in ["m_above_mhhw_p50", "pct_below_0.6",
                                "pct_below_1.5", "pct_leveed", "crop_08_12", "crop_21_25",
                                "wetland_21_25"]}}
                         for g, d in t.groupby("group")}).T  # fmt: skip
    summ.index.name = "group (area-weighted)"

    lines = ["# NRCS easements vs tidal exposure (2026-10-05)", "",
             "Generated by `scripts/easement_exposure.py`; easements from the NRCS Stewardship "
             "Lands Inventory service (`scripts/fetch_easements.py`; NO enrollment dates). "
             "Exposure grid and MHHW surface as `reports/bayshore_exposure.md`; % are of each "
             "easement's area on the DEM.", "",
             "## By group", "", md_table(summ.round(2), floatfmt="{:.2f}"), "",
             "## Wetland-type easements", "",
             md_table(t[t.group == "wetland"].sort_values("km2", ascending=False)
                      .set_index("id").round(2), floatfmt="{:.2f}"), "",
             "## Imagery spot-check samples inside an easement", "",
             md_table(in_e.set_index("id")) if len(in_e) else "None.", "",
             "## All easements", "",
             md_table(t.sort_values(["group", "km2"], ascending=[False, False]).set_index("id")
                      .round(2), floatfmt="{:.2f}"), ""]  # fmt: skip
    text = "\n".join(lines)
    (config.REPORTS / "easement_exposure.md").write_text(text + "\n")
    print(text)

    # map: exposure classes as in bayshore_exposure, easements outlined by group
    cty = region.load_counties().to_crs(G.crs)
    cty = cty[cty.fips.isin(domain.COUNTIES)]
    fig, ax = plt.subplots(figsize=(9, 11))
    tr, shape = G.tr, G.shape
    ext = (tr.c, tr.c + tr.a * shape[1], tr.f + tr.e * shape[0], tr.f)
    low = np.where(ok & (G.hab < 1.5), np.digitize(G.hab, [0.0, 0.6]), np.nan)
    ax.imshow(np.where(ok, 1, np.nan), extent=ext, cmap=matplotlib.colors.ListedColormap(["#eeeeee"]))
    ax.imshow(low, extent=ext, cmap=matplotlib.colors.ListedColormap(["#9ecae1", "#c6dbef", "#deebf7"]),
              vmin=-0.5, vmax=2.5, interpolation="nearest")  # fmt: skip
    cty.boundary.plot(ax=ax, color="#555555", lw=1.0, ls="--")
    lev.boundary.plot(ax=ax, color="k", lw=0.5)
    for g, c in (("farmland", "#d95f02"), ("other", "#7570b3"), ("wetland", "#1b9e77")):
        d = e[e.group == g]
        if len(d):
            d.plot(ax=ax, facecolor=c, edgecolor=c, alpha=0.8, lw=1.2)
            ax.plot([], [], "s", color=c, ms=9, label=f"NRCS {g} easement ({len(d)})")
    for lab_, c in (("below MHHW", "#9ecae1"), ("0-0.6 m above", "#c6dbef"), ("0.6-1.5 m above", "#deebf7")):
        ax.plot([], [], "s", color=c, ms=9, label=f"ground {lab_}")
    ax.plot([], [], "-", color="k", lw=0.8, label="NLD leveed area")
    ax.legend(loc="lower left", fontsize=8, framealpha=0.9)
    ax.set_xlim(ext[0], ext[1]), ax.set_ylim(ext[2], ext[3])
    ax.set_xticks([]), ax.set_yticks([])
    ax.set_title("NRCS easements and low ground (height above recent MHHW)")
    fig.tight_layout()
    out = config.REPORTS / "figs" / "easement_exposure.png"
    fig.savefig(out, dpi=150)
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
