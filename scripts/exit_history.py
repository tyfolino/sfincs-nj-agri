"""Leaving farming in the historical record, NJ and Delaware side by side (plan step 5c): does
Delaware's bayshore show the exit pattern Seowoo found in NJ, before any flood model?

Fields: agri_sfincs.fields (each state's LU/LC polygons farmed in 2012), kept when they were
mostly cropland in 2008-12 (mean CDL cropland >= CROP_MIN): the "crop fields".

Per state, from CDL 2008-2025 (agri_sfincs.cdl.field_years, pixel centre in polygon):
  left cropland   agri_sfincs.panel.left_cropland: >= 50% cropland in t-1, < 50% in t and t+1
                  (the storm panel's exit, FINDINGS §37); per year, the share of the crop
                  fields at risk that leave (area weighted), and by median height above recent
                  MHHW (agri_sfincs.exposure on the side's bed, FINDINGS §21)
  CDL 2024        CDL's 2024 product change shows as a drop in cropland on every field
                  (FINDINGS §37): 2024 (and 2025, which has no t+1) are flagged, not dropped
From LU/LC: the share of 2012 farm area no longer farmed at each later edition, by county.

Writes data/analysis/exit_history/{fields,field_year}_<state>.csv and reports/exit_history.md.
Usage:  python scripts/exit_history.py [--states NJ DE]
"""

from __future__ import annotations

import argparse

import numpy as np
import pandas as pd

from agri_sfincs import cdl, config, domain, exposure, fields, landuse, panel
from agri_sfincs.report import md_table

OUT = config.ANALYSIS_DIR / "exit_history"
YEARS = range(2008, 2026)
EARLY = range(2008, 2013)
CROP_MIN = 0.5
HEIGHT_BANDS = [(-99, 1.5, "< 1.5 m"), (1.5, 3.0, "1.5-3 m"), (3.0, 999, "> 3 m")]
FIPS = {sd.state: sd.state_fips for sd in domain.SIDES.values()}
SIDE_OF = {sd.state: sd.key for sd in domain.SIDES.values()}


def heights(state: str, g) -> pd.Series:
    """Median ground height above recent MHHW per field (agri_sfincs.exposure, the side's bed),
    NaN until the side's bed_merged exists."""
    side = SIDE_OF[state]
    if not (config.ELEV_DIR / f"bed_merged{domain.side(side).files}.tif").exists():
        return pd.Series(np.nan, index=g.field_id.values)
    return pd.Series(exposure.add_exposure(g, side).m_above_mhhw.values, index=g.field_id.values)


def build(state: str) -> tuple[pd.DataFrame, pd.DataFrame]:
    g = fields.load(state)
    static, fy, missing = cdl.field_years(g, YEARS, FIPS[state])
    if missing:
        print(f"  {state}: CDL missing for {missing}")
    f = g.drop(columns="geometry").set_index("field_id").join(static)
    f["m_above_mhhw"] = heights(state, g)
    crop = fy.pivot(index="field_id", columns="year", values="cropland")
    f["crop_early"] = crop[[y for y in EARLY if y in crop]].mean(axis=1)
    f["crop_field"] = f.crop_early >= CROP_MIN
    left = panel.left_cropland(crop).stack().rename("left_cropland")
    fy = fy.merge(left.reset_index(), on=["field_id", "year"], how="left")
    OUT.mkdir(parents=True, exist_ok=True)
    f.to_csv(OUT / f"fields_{state}.csv", float_format="%.6g")
    fy.to_csv(OUT / f"field_year_{state}.csv", index=False, float_format="%.6g")
    return f, fy


def yearly(f: pd.DataFrame, fy: pd.DataFrame, sel=None) -> pd.Series:
    """% of crop-field area at risk (>= 50% cropland the year before) that leaves, per year."""
    keep = f.index[f.crop_field & (True if sel is None else sel)]
    d = fy[fy.field_id.isin(keep) & fy.left_cropland.notna()].merge(f[["ha"]], left_on="field_id", right_index=True)
    return 100 * d.groupby("year").apply(lambda x: (x.left_cropland * x.ha).sum() / x.ha.sum(), include_groups=False)


def lulc_left(state: str, f: pd.DataFrame) -> pd.DataFrame:
    _, _, _, mid, last = fields.EDITIONS[state]
    out = {}
    for y in (mid, last):
        gone = ~f[f"lulc{y}"].map(landuse.is_farmed, na_action="ignore").fillna(False).astype(bool)
        out[f"not farmed {y}, %"] = 100 * f.ha[gone].groupby(f.county).sum() / f.ha.groupby(f.county).sum()
    t = pd.DataFrame(out)
    t["2012 farm ha"] = f.ha.groupby(f.county).sum()
    return t


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--states", nargs="*", default=["NJ", "DE"])
    a = ap.parse_args()
    built = {s: build(s) for s in a.states}

    cols = {}
    for s, (f, fy) in built.items():
        cols[f"{s} crop fields"] = yearly(f, fy)
        if f.m_above_mhhw.notna().any():
            for lo, hi, lab in HEIGHT_BANDS:
                cols[f"{s} {lab}"] = yearly(f, fy, f.m_above_mhhw.between(lo, hi, inclusive="left"))
    t = pd.DataFrame(cols)
    t.index = [f"{y}{' (CDL change)' if y >= panel.CDL_CHANGE else ''}" for y in t.index]
    pre = pd.DataFrame(cols).loc[lambda d: d.index < panel.CDL_CHANGE]

    lines = ["# Leaving farming in the historical record: NJ and Delaware (CDL 2008-2025)", "",
             "Generated by `scripts/exit_history.py` (method in its docstring). Fields = each state's "
             "LU/LC farm polygons of 2012 in the model watersheds that were >= 50% CDL cropland in "
             "2008-12. An exit in year t = >= 50% cropland in t-1, < 50% in t and t+1 (the storm "
             "panel's `left_cropland`). Numbers are % of the area at risk that year.", ""]
    for s, (f, _) in built.items():
        lines.append(f"- {s}: {int(f.crop_field.sum()):,} crop fields, {f.ha[f.crop_field].sum():,.0f} ha "
                     f"(of {len(f):,} farm polygons, {f.ha.sum():,.0f} ha)")
    lines += ["", "## Exits per year, % of crop-field area at risk", "",
              md_table(t.round(2), floatfmt="{:.2f}"), "",
              "2024: CDL's product change (FINDINGS §37), not only land change. 2025 has no t+1.", "",
              "## Mean exit rate 2009-2023, % per year", "", md_table(pre.mean().to_frame("mean").T.round(2),
                                                                     floatfmt="{:.2f}"), ""]  # fmt: skip
    for s, (f, _) in built.items():
        lines += [f"## {s}: 2012 farm area no longer farmed in later LU/LC editions (all farm polygons)", "",
                  md_table(lulc_left(s, f).round(1), floatfmt="{:,.1f}"), ""]
    text = "\n".join(lines)
    (config.REPORTS / "exit_history.md").write_text(text + "\n")
    print(text)


if __name__ == "__main__":
    main()
