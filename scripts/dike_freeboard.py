"""Dike crest vs storm-tide level: how much of each bank sits below a Sandy-class peak, today
and with sea-level rise? (A static check before the SFINCS dike scenarios.)

Crests: data/structures/dikes_built.gpkg layer crest_points (scripts/build_dikes.py: the
lidar ridge, max of the bed within ±20 m, every 5 m; notches filled on farm systems).
Storm level: the Hurricane Sandy peak (2012-10-25 .. 11-03) at each forcing gauge (observed
hourly, m NAVD88), spread by inverse-distance weighting (Cape May left out: ocean side).
In the bay Sandy's peak (~1.9 m) is typical of the largest storm tides of 2002-2025
(2016-01-23 1.92 m, 2012-12-21 1.90 m, 2021-10-29 1.87 m at Ship John Shoal).

Freeboard = crest - storm level; km of bank with freeboard < 0, < +0.3, < +0.6, < +1.0 m
(= overtopped by a Sandy peak today, at +0.3 / +0.6 / +1.0 m of sea-level rise).

Caveats: the lidar may miss a narrow crest's top and predates any raising after Sandy; an
hourly peak overtopping briefly is not a breach. SFINCS gives the volumes.

Writes reports/dike_freeboard.md. Usage:  python scripts/dike_freeboard.py
"""

from __future__ import annotations

import geopandas as gpd
import pandas as pd
import xarray as xr

from agri_sfincs import config, domain, exposure
from agri_sfincs.report import md_table

SANDY = ("2012-10-25", "2012-11-03")
SLR = [0.0, 0.3, 0.6, 1.0]
SPACING_KM = 0.005


def main() -> None:
    c = gpd.read_file(config.STRUCT_DIR / "dikes_built.gpkg", layer="crest_points")
    with xr.open_dataset(config.GAUGE_DIR / "waterlevel_forcing_navd88.nc") as ds:
        peak = ds.waterlevel.sel(time=slice(*SANDY)).max("time")
        st = pd.DataFrame({"lon": ds.lon.values, "lat": ds.lat.values, "v": peak.values},
                          index=ds.stations.values.astype(str)).drop(domain.CAPE_MAY)  # fmt: skip
    p = c.to_crs(domain.EPSG)
    c["sandy"] = exposure.idw(st, "v", p.geometry.x.values, p.geometry.y.values, f"EPSG:{domain.EPSG}")
    c["free"] = c.crest - c.sandy

    def summary(d):
        out = {"km": len(d) * SPACING_KM, "crest p10": d.crest.quantile(0.1),
               "crest median": d.crest.median(), "Sandy peak": d.sandy.mean()}  # fmt: skip
        for s in SLR:
            out[f"km below Sandy{'' if s == 0 else f' +{s:g}'}"] = (d.free < s).sum() * SPACING_KM
        return pd.Series(out)

    by = c.groupby(["system", "farm"]).apply(summary, include_groups=False)
    by = by.sort_values("km below Sandy +0.3", ascending=False).round(2)
    tot = c.groupby("farm").apply(summary, include_groups=False).round(2)
    tot.index = ["other levees" if not f else "farm levees" for f in tot.index]
    lines = ["# Dike crests vs a Sandy-class storm tide (2026-10-05)", "",
             "Generated by `scripts/dike_freeboard.py` (method and caveats in its docstring). "
             "Crest = lidar ridge; storm level = Sandy's observed peak, IDW between the bay gauges.", "",
             "## Totals", "", md_table(tot, floatfmt="{:.2f}"), "",
             "## By levee system (farm = it protects > 0.1 km² of cropland)", "",
             md_table(by, floatfmt="{:.2f}"), ""]  # fmt: skip
    text = "\n".join(lines)
    (config.REPORTS / "dike_freeboard.md").write_text(text + "\n")
    print(text)


if __name__ == "__main__":
    main()
