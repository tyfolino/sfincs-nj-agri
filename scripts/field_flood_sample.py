"""Sample per-field flood table for ONE scenario run, for the ag-econ team: what each farm
field grows (CDL) and when / how long / how deep it floods (SFINCS), in the shape a Hazus-style
crop damage calculation needs (start date, duration, depth).

Fields and their ids = data/analysis/field_flood_classes.gpkg (scripts/field_flood_classes.py:
agri_sfincs.fields, NJDEP LU/LC farm polygons of 2012); the output keeps those still farmed in
2020. Depth per 10 m pixel per day = zsmax of its model cell - the
pixel's ground, as field_flood_classes.py. A field is WET on a day when >= fieldflood.SHARE (10%)
of its pixels are > 5 cm deep that day; it FLOODS in the run when >= 10% of its pixels are
> 5 cm on at least one day (the §29 rule, so `flooded` matches field_flood_classes.csv).

Crop = CDL of the event year on the same polygons (30 m pixels, by centre).

Writes data/analysis/sample_<run>/: fields.gpkg (polygons + summary), fields.csv (same, no
geometry), daily.csv (flooded fields only: per day flooded % and mean depth) and README.md.
Usage:  python scripts/field_flood_sample.py [--dikes intact] [--slr 60]
"""

from __future__ import annotations

import argparse

import geopandas as gpd
import numpy as np
import pandas as pd
import rasterio
import xarray as xr
from rasterio.features import rasterize
from rasterio.windows import from_bounds

from agri_sfincs import cdl, config, fieldflood, runs
from agri_sfincs.events import EVENTS

EVENT = "tide2024oct"
THRESH = runs.THRESH
MIN_PCT = 5  # crops listed in cdl_crops when they cover >= this % of the field


def crops(g: gpd.GeoDataFrame, year: int) -> pd.DataFrame:
    """Per field: CDL main class (any class) and its %, cropland %, pasture %, and the crop
    classes covering >= MIN_PCT %."""
    with rasterio.open(cdl.path(year)) as src:
        gg = g.to_crs(src.crs)
        win = from_bounds(*gg.total_bounds, transform=src.transform).round_offsets().round_lengths()
        code = src.read(1, window=win)
        tr = src.window_transform(win)
    ids = rasterize(zip(gg.geometry, gg.field_id), out_shape=code.shape, transform=tr, fill=0, dtype="uint32")
    m = ids > 0
    t = pd.DataFrame({"field_id": ids[m], "code": code[m]}).value_counts().rename("n").reset_index()
    t["pct"] = 100 * t.n / t.groupby("field_id").n.transform("sum")
    t = t.sort_values(["field_id", "pct"], ascending=[True, False])
    main = t.groupby("field_id").first()
    crop = t[t.code.isin(cdl.CROPLAND)]
    listed = crop[crop.pct >= MIN_PCT].groupby("field_id").apply(
        lambda d: "; ".join(f"{cdl.NAMES.get(c, c)} {p:.0f}%" for c, p in zip(d.code, d.pct)), include_groups=False)
    out = pd.DataFrame({
        f"cdl{year}_main": main.code.map(lambda c: cdl.NAMES.get(c, str(c))),
        f"cdl{year}_main_pct": main.pct.round(0),
        f"cdl{year}_cropland_pct": crop.groupby("field_id").pct.sum().reindex(main.index).fillna(0).round(0),
        f"cdl{year}_pasture_pct": t[t.code.isin(cdl.PASTURE)].groupby("field_id").pct.sum()
                                   .reindex(main.index).fillna(0).round(0),
        f"cdl{year}_crops": listed.reindex(main.index).fillna(""),
    })  # fmt: skip
    return out.reindex(g.field_id)


def daily(run, f_sel, d_sel, fid, n):
    """Per focus day x field: % of pixels > 5 cm, mean depth over those pixels; and per
    field the month-max % (pixels > 5 cm on any day) and mean month-max depth over them."""
    with xr.open_dataset(run / "sfincs_map.nc") as mp:
        day = runs.block_days(mp)
        focus = EVENTS[EVENT].in_focus(day)
        npx = np.bincount(fid, minlength=n + 1).astype(float)
        maxd = np.zeros(f_sel.size, "float32")
        pct, dep, dates = [], [], []
        for k in np.flatnonzero(focus):
            h = runs.depth(mp, k, f_sel, d_sel)
            maxd = np.maximum(maxd, h)
            w = h > THRESH
            nw = np.bincount(fid, weights=w, minlength=n + 1)
            with np.errstate(invalid="ignore", divide="ignore"):
                pct.append(100 * nw / npx)
                dep.append(np.bincount(fid, weights=np.where(w, h, 0), minlength=n + 1) / nw)
            dates.append(day[k])
    fl = maxd > THRESH
    nfl = np.bincount(fid, weights=fl, minlength=n + 1)
    with np.errstate(invalid="ignore", divide="ignore"):
        month_pct = 100 * nfl / npx
        month_dep = np.bincount(fid, weights=np.where(fl, maxd, 0), minlength=n + 1) / nfl
    return (pd.DatetimeIndex(dates), np.array(pct)[:, 1:], np.array(dep)[:, 1:],
            month_pct[1:], month_dep[1:])  # fmt: skip


def readme(name: str, dk: str, slr: int, year: int, g: pd.DataFrame) -> str:
    f = g[g.flooded]
    return f"""# Sample flood data: one scenario, per farm field

Scenario `{name}`: SFINCS model, ordinary tides of October 2024 (no rain), sea level
raised by {slr / 100:.1f} m, dikes {runs.DIKES[dk]}. Generated by `scripts/field_flood_sample.py`.

Fields: {len(g):,} NJDEP land-use 2020 farm polygons in Salem, Cumberland and Gloucester
({g.ha.sum():,.0f} ha). **{len(f):,} fields ({f.ha.sum():,.0f} ha) flood in this scenario**;
the flooded part of them is {f.flooded_ha.sum():,.0f} ha.

## Files

- `fields.gpkg`: field polygons (EPSG:{g.crs.to_epsg()}) with the columns below.
- `fields.csv`: the same table without geometry.
- `daily.csv`: flooded fields only, one row per field per day of October 2024.

## Columns (`fields`)

| column | meaning |
|---|---|
| field_id | field id (same ids as `field_flood_classes.csv`) |
| county, ha | county, field area (hectares) |
| lulc2020 | NJDEP land-use code; 2140 = "agricultural wetland", wet farmland |
| behind_levee | at least half the field inside a mapped levee-protected area (USACE NLD) |
| flood_class | when the field first floods across all the scenarios (today, +0.3, +0.6, +1.0 m; with/without dikes) |
| cdl{year}_main, _main_pct | the most common USDA CDL {year} class on the field, and its % of the field |
| cdl{year}_cropland_pct | % of the field CDL calls cropland (pasture, wetland, forest, etc. excluded; hay included) |
| cdl{year}_pasture_pct | % of the field CDL calls Grass/Pasture (class 176). Add it to cropland_pct for a crop-or-pasture share. CDL's pasture class also takes idle and abandoned grassy fields and is less accurate than its crop classes |
| cdl{year}_crops | crop classes covering >= {MIN_PCT}% of the field |
| flooded | at least 10% of the field is > 5 cm deep on at least one day |
| flooded_pct, flooded_ha | share / area of the field > 5 cm deep on at least one day |
| first_flood_date, last_flood_date | first / last day the field is flooded (>= 10% of it > 5 cm) |
| flood_days | number of days in the month the field is flooded |
| longest_run_days | most consecutive flooded days (the "duration" in Hazus-style crop tables) |
| depth_m | mean of the month's maximum depth over the flooded part (m) |
| water | source of the water: tidal (brackish / salt) |

`daily.csv`: field_id, date, flooded_pct (share of the field > 5 cm that day), depth_m (mean
depth over that flooded part).

## Read with care

- **Tidal water comes and goes.** The model keeps each day's HIGHEST water. A field wet at
  high tide and dry at low tide counts as flooded that day. For tidal flooding the days and
  durations are an upper bound on standing water.
- **One month, one season.** October is after most harvests; the same tides in July would hit
  standing crops. The dates here describe this month only.
- **Salt.** Hazus crop tables assume fresh water. Brackish water also harms the soil for
  later seasons, which no single-year crop table covers.
- **CDL and the wettest fields disagree.** Much of the low-lying farmland (land-use 2140) is
  wetland or grass in CDL, so it shows little or no crop.
- The 10% / 5 cm thresholds are choices; `flooded_pct` and `daily.csv` let you set your own.
"""


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dikes", default="intact", choices=list(runs.DIKES))
    ap.add_argument("--slr", type=int, default=60, help="sea-level rise, cm")
    a = ap.parse_args()
    run = runs.run_dir(EVENT, a.dikes, a.slr)
    year = EVENTS[EVENT].focus_start.year

    src = gpd.read_file(config.ANALYSIS_DIR / "field_flood_classes.gpkg")
    g = src[["field_id", "county", "lulc2020", "farmed2020", "ha", "behind_levee", "cls", "geometry"]]
    g = g.rename(columns={"cls": "flood_class"}).sort_values("field_id").reset_index(drop=True)
    assert (g.field_id.values == np.arange(1, len(g) + 1)).all()
    n = len(g)

    f_sel, d_sel, fid = fieldflood.field_pixels(g)
    dates, pct, dep, month_pct, month_dep = daily(run, f_sel, d_sel, fid, n)
    wet = pct >= 100 * fieldflood.SHARE  # day x field
    anyw = wet.any(axis=0)
    first = np.where(anyw, wet.argmax(axis=0), -1)
    last = np.where(anyw, len(dates) - 1 - wet[::-1].argmax(axis=0), -1)

    g = g.join(crops(g, year), on="field_id")
    g["flooded"] = month_pct >= 100 * fieldflood.SHARE
    g["flooded_pct"] = np.nan_to_num(month_pct).round(1)
    g["flooded_ha"] = (g.ha * g.flooded_pct / 100).round(2)
    g["first_flood_date"] = pd.Series(dates[first].date, dtype="object").where(first >= 0)
    g["last_flood_date"] = pd.Series(dates[last].date, dtype="object").where(last >= 0)
    g["flood_days"] = wet.sum(axis=0)
    g["longest_run_days"] = [fieldflood.longest_run(wet[:, i]) for i in range(n)]
    g["depth_m"] = np.where(g.flooded, month_dep, np.nan).round(3)
    g["water"] = "tidal"
    g["ha"] = g.ha.round(2)

    # A field can flood (10% over the month) without 10% on any single day: no dates for it.
    odd = int((g.flooded & ~anyw).sum())

    keep = g.farmed2020.values
    g, pct, dep = g[keep].reset_index(drop=True), pct[:, keep], dep[:, keep]
    anyw = anyw[keep]
    name = run.name
    out = config.ANALYSIS_DIR / f"sample_{name}"
    out.mkdir(parents=True, exist_ok=True)
    g.to_file(out / "fields.gpkg", driver="GPKG")
    g.drop(columns="geometry").to_csv(out / "fields.csv", index=False)
    idx = np.flatnonzero(g.flooded.values)
    d = pd.DataFrame({
        "field_id": np.tile(g.field_id.values[idx], len(dates)),
        "date": np.repeat(dates.date, idx.size),
        "flooded_pct": pct[:, idx].ravel().round(1),
        "depth_m": dep[:, idx].ravel().round(3),
    }).sort_values(["field_id", "date"])  # fmt: skip
    d.to_csv(out / "daily.csv", index=False)
    (out / "README.md").write_text(readme(name, a.dikes, a.slr, year, g))

    f = g[g.flooded]
    print(f"{name}: {len(f)} of {n} fields flood ({f.ha.sum():,.0f} ha; flooded part {f.flooded_ha.sum():,.0f} ha)")
    print(f"  flooded fields with no single day >= 10%: {odd}")
    print(f"  flooded ha by county:\n{f.groupby('county').flooded_ha.sum().round(0)}")
    print(f"  flooded fields by CDL main class:\n{f.groupby(f'cdl{year}_main').ha.agg(['size', 'sum']).round(0)}")
    crop, past = f[f"cdl{year}_cropland_pct"], f[f"cdl{year}_pasture_pct"]
    for lab, share in [("cropland", crop), ("cropland + pasture", crop + past)]:
        h = f[share >= 50]
        print(f"  flooded fields >= 50% {lab}: {len(h)} ({h.flooded_ha.sum():,.0f} ha flooded)")
    print(f"  longest run (days): {f.longest_run_days.describe().round(1).to_dict()}")
    print(f"  wrote {out}")


if __name__ == "__main__":
    main()
